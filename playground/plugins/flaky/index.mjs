// Первая активация в процессе хоста падает: так в окне видна заглушка с причиной, а «Включить снова» поднимает плагин.
let attempts = 0;

export default {
  activate(ctx) {
    attempts += 1;
    if (attempts === 1) throw new Error('первый запуск в хосте всегда падает (демо)');
    ctx.log(`поднялся с попытки ${attempts}`);
  },
};
